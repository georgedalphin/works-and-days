import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--use-gl=swiftshader","--enable-unsafe-swiftshader"])
        pg = await b.new_page(viewport={"width":960,"height":640})
        errs=[]
        pg.on("pageerror", lambda e: errs.append(str(e)))
        await pg.goto("file:///home/claude/works-and-days/dist/index.html")
        await pg.wait_for_timeout(1200)
        await pg.mouse.click(480,320)
        # choose New life (last option)
        await pg.keyboard.press("ArrowDown"); await pg.keyboard.press("Enter"); await pg.wait_for_timeout(1000)
        if await pg.evaluate("game.scene.isActive('Creation')"): await pg.evaluate("(()=>{const c=game.scene.getScene('Creation');for(const a of Object.keys(c.aretai))c.aretai[a]=3;c.finish();})()"); await pg.wait_for_timeout(1800)
        await pg.keyboard.press("Escape"); await pg.wait_for_timeout(300)
        print("scene", await pg.evaluate("[G.data.scene, game.scene.getScene('UI').modal, game.scene.getScene('House').player.y]"))
        # walk out of hut
        await pg.keyboard.down("s"); await pg.wait_for_timeout(1600); await pg.keyboard.up("s")
        await pg.wait_for_timeout(700)
        print("scene", await pg.evaluate("G.data.scene"))
        # teleport near plot: tile (28,13) facing right -> (29,13)
        async def tp(tx,ty,facing):
            await pg.evaluate(f"(()=>{{const s=game.scene.getScene('Farm');s.player.setPosition({tx}*16+8,{ty}*16+3);s.facing={facing};}})()")
            await pg.wait_for_timeout(100)
        await tp(28,13,2)
        await pg.keyboard.press("1"); await pg.wait_for_timeout(100)
        await pg.keyboard.press("Space"); await pg.wait_for_timeout(200)
        print("ground", await pg.evaluate("JSON.stringify(G.data.ground)"))
        await pg.keyboard.press("2"); await pg.wait_for_timeout(100)
        print("sel", await pg.evaluate("G.data.selected"), "water", await pg.evaluate("G.data.jarWater"))
        await pg.keyboard.press("Space"); await pg.wait_for_timeout(200)
        print("ground", await pg.evaluate("JSON.stringify(G.data.ground)"), "water", await pg.evaluate("G.data.jarWater"))
        await pg.screenshot(path="/home/claude/test/20_till.png")
        # well: stand at (30,11) facing up -> (30,10)
        await tp(30,11,3)
        await pg.keyboard.press("Space"); await pg.wait_for_timeout(200)
        print("water after well", await pg.evaluate("G.data.jarWater"))
        print("prompt", await pg.evaluate("game.scene.getScene('UI').promptText.text"))
        # door prompt
        await tp(24,11,3)
        await pg.wait_for_timeout(100)
        print("prompt door", await pg.evaluate("game.scene.getScene('UI').promptText.text"))
        # find a brush tile and sickle it
        pos = await pg.evaluate("(()=>{const s=game.scene.getScene('Farm');for(let y=3;y<33;y++)for(let x=3;x<45;x++){const t=s.objects.getTileAt(x,y);const l=s.objects.getTileAt(x-1,y);if(t&&t.index===4&&(!l||l.index===-1))return [x,y];}})()")
        print("brush at", pos)
        await tp(pos[0]-1,pos[1],2)
        await pg.keyboard.press("3"); await pg.keyboard.press("Space"); await pg.wait_for_timeout(200)
        print("fiber", await pg.evaluate("G.count('Fiber')"))
        await pg.screenshot(path="/home/claude/test/21_sickle.png")
        # inventory
        await pg.keyboard.press("i"); await pg.wait_for_timeout(300)
        await pg.screenshot(path="/home/claude/test/22_inv.png")
        print("modal", await pg.evaluate("game.scene.getScene('UI').modal"))
        await pg.evaluate("(()=>{const u=game.scene.getScene('UI');u.clickSlot(0);u.clickSlot(15);})()")
        print("slots0/15", await pg.evaluate("JSON.stringify([G.data.slots[0],G.data.slots[15]])"))
        await pg.keyboard.press("Tab"); await pg.wait_for_timeout(200)
        print("modal after close", await pg.evaluate("game.scene.getScene('UI').modal"))
        await pg.keyboard.press("0"); await pg.wait_for_timeout(100)
        print("sel 0 key ->", await pg.evaluate("G.data.selected"))
        await pg.screenshot(path="/home/claude/test/23_after.png")
        print("ERRORS:", errs)
        await b.close()
asyncio.run(main())
